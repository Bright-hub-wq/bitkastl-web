// Every file in ./langs is loaded automatically. The file name is the language code.
const files = import.meta.glob("./langs/*.ts", { eager: true }) as Record<string, Record<string, Record<Key, string>>>;
const loaded: Partial<Record<Lang, Record<Key, string>>> = {};
for (const [path, mod] of Object.entries(files)) {
    const code = path.split("/").pop()!.replace(".ts", "") as Lang;
    const dict = Object.values(mod)[0];
    if (dict) loaded[code] = dict;
}

export const translations: Partial<Record<Lang, Record<Key, string>>> & { en: Record<Key, string> } = {
    en, fr, es, pt, ...loaded,
};

export const LANGS: { code: Lang; label: string }[] = ORDER
    .filter((c) => translations[c])
    .map((c) => ({ code: c, label: LABELS[c] }));

